// Compiles texts/*.tex (public-domain sources) into src/data/fulltexts.ts,
// which the reader page (text/[id]/read) uses to show the full book text.
//
// Each .tex file carries a metadata header:
//   % !atlas-meta ... % !end-atlas-meta
// and a body delimited by:
//   % !body-start ... % !body-end
//
// Run:  node texts/build-fulltexts.mjs
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const dir = dirname(fileURLToPath(import.meta.url));
const outFile = join(dir, '..', 'src', 'data', 'fulltexts.ts');

function parseMeta(src) {
  const m = src.match(/% !atlas-meta([\s\S]*?)% !end-atlas-meta/);
  const meta = {};
  if (m) {
    for (const line of m[1].split('\n')) {
      const kv = line.match(/^%\s*([A-Za-z]+):\s*(.*)$/);
      if (kv) meta[kv[1]] = kv[2].trim();
    }
  }
  return meta;
}

function parseBody(src) {
  const m = src.match(/% !body-start([\s\S]*?)% !body-end/);
  return m ? m[1].trim() : '';
}

const files = readdirSync(dir).filter(f => f.endsWith('.tex') && !f.startsWith('_'));
const entries = {};
let count = 0, paras = 0;
for (const f of files) {
  const src = readFileSync(join(dir, f), 'utf8');
  const meta = parseMeta(src);
  const body = parseBody(src);
  if (!meta.id || !body) { console.warn(`  skip ${f}: missing id or body markers`); continue; }
  const pCount = (body.match(/\\para/g) || []).length;
  entries[meta.id] = {
    id: meta.id,
    title: meta.title || meta.id,
    author: meta.author || '',
    authorName: meta.authorName || '',
    language: meta.language || 'English',
    sourceLanguage: meta.sourceLanguage || '',
    translator: meta.translator || '',
    translationYear: meta.translationYear || '',
    source: meta.source || '',
    license: meta.license || 'Public Domain',
    status: meta.status || 'complete',
    paragraphs: pCount,
    tex: body,
  };
  count++; paras += pCount;
}

const header = `// AUTO-GENERATED by texts/build-fulltexts.mjs — do not edit by hand.
// Full public-domain text bodies (LaTeX) keyed by text id, shown in text/[id]/read.
export interface FullText {
  id: string; title: string; author: string; authorName: string;
  language: string; sourceLanguage: string; translator: string; translationYear: string;
  source: string; license: string; status: string; paragraphs: number; tex: string;
}
export const fullTexts: Record<string, FullText> = `;

writeFileSync(outFile, header + JSON.stringify(entries, null, 2) + ';\n');
console.log(`Wrote ${count} full texts (${paras} paragraphs) → src/data/fulltexts.ts`);
